package phpfpm

import (
	"fmt"
	"log/slog"
	"os"
	"os/exec"
	"regexp"
	"strings"
)

// Per-site resource isolation via a dedicated systemd PHP-FPM service.
//
// Why: real per-site CPU/RAM limits need cgroup v2. cgroup membership is
// inherited on fork, so all of a site's PHP workers land in the right cgroup
// ONLY if their FPM master has its own cgroup. The shared php{ver}-fpm.service
// runs one master for ALL sites → can't subdivide. So a site that needs a
// limit gets its OWN master: wpm-fpm@{domain}.service, which systemd places in
// its own cgroup, and `CPUQuota=`/`MemoryMax=` then apply to that site alone.
//
// Design: on-demand. Only sites WITH a limit get a dedicated service. The
// dedicated master listens on the SAME socket the shared pool used
// (/var/run/php/php{ver}-fpm-{domain}.sock) so the Nginx vhost never changes.

const (
	templatePath = "/etc/systemd/system/wpm-fpm@.service"
	wpmFPMDir    = "/etc/wpm-fpm"
)

var phpVerRe = regexp.MustCompile(`^\d+\.\d+$`)

// systemd template unit. ${FPM_BIN}/${FPM_CONF} are expanded from the
// per-instance EnvironmentFile so one template serves every PHP version.
const templateUnit = `# Auto-generated by wp-manage — do not edit.
[Unit]
Description=WP Manage dedicated PHP-FPM (%i)
After=network.target

[Service]
Type=simple
EnvironmentFile=/etc/wpm-fpm/%i.env
ExecStart=${FPM_BIN} --nodaemonize --fpm-config ${FPM_CONF}
ExecReload=/bin/kill -USR2 $MAINPID
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
`

// EnsureFPMTemplate installs the template unit if missing or stale. Idempotent.
func EnsureFPMTemplate() error {
	if existing, err := os.ReadFile(templatePath); err == nil && string(existing) == templateUnit {
		return nil // already up to date
	}
	if err := os.WriteFile(templatePath, []byte(templateUnit), 0644); err != nil {
		return fmt.Errorf("write template unit: %w", err)
	}
	exec.Command("systemctl", "daemon-reload").Run()
	slog.Info("wpm-fpm template unit installed")
	return nil
}

// ApplyResourceLimit converts a site to its dedicated FPM service (if not
// already) and applies CPUQuota/MemoryMax. cpuPct=200 → 2 cores; 0 → no CPU
// cap. memMB=0 → no memory cap. Safe to call repeatedly to change limits.
func ApplyResourceLimit(domain, phpVersion string, cpuPct uint, memMB uint64) error {
	if !phpVerRe.MatchString(phpVersion) {
		return fmt.Errorf("invalid php version %q", phpVersion)
	}
	if err := EnsureFPMTemplate(); err != nil {
		return err
	}

	siteDir := fmt.Sprintf("%s/%s", wpmFPMDir, domain)
	sharedPool := fmt.Sprintf("/etc/php/%s/fpm/pool.d/%s.conf", phpVersion, domain)
	disabledPool := sharedPool + ".disabled"

	alreadyIsolated := serviceExists(domain)

	if !alreadyIsolated {
		// First-time isolation: migrate the shared pool into the dedicated service.
		poolContent, err := os.ReadFile(sharedPool)
		if err != nil {
			// Pool might already be disabled from a prior partial run.
			if c, err2 := os.ReadFile(disabledPool); err2 == nil {
				poolContent = c
			} else {
				return fmt.Errorf("read shared pool %s: %w", sharedPool, err)
			}
		}

		if err := os.MkdirAll(siteDir, 0755); err != nil {
			return fmt.Errorf("mkdir %s: %w", siteDir, err)
		}
		// pool.conf — verbatim copy (keeps same user/group/socket → nginx unchanged)
		if err := os.WriteFile(siteDir+"/pool.conf", poolContent, 0644); err != nil {
			return fmt.Errorf("write pool.conf: %w", err)
		}
		// global php-fpm.conf
		global := fmt.Sprintf(`[global]
pid = /run/wpm-fpm-%s.pid
error_log = /var/log/wpm-fpm-%s.log
daemonize = no
include = %s/pool.conf
`, domain, domain, siteDir)
		if err := os.WriteFile(siteDir+"/php-fpm.conf", []byte(global), 0644); err != nil {
			return fmt.Errorf("write php-fpm.conf: %w", err)
		}
		// per-instance env (PHP binary + config path)
		env := fmt.Sprintf("FPM_BIN=/usr/sbin/php-fpm%s\nFPM_CONF=%s/php-fpm.conf\n", phpVersion, siteDir)
		if err := os.WriteFile(fmt.Sprintf("%s/%s.env", wpmFPMDir, domain), []byte(env), 0644); err != nil {
			return fmt.Errorf("write env file: %w", err)
		}

		// Remove the pool from the shared master, free the socket.
		os.Rename(sharedPool, disabledPool)
		exec.Command("systemctl", "reload", fmt.Sprintf("php%s-fpm", phpVersion)).Run()
		// Stale socket can linger after reload; php-fpm re-binds on start, but
		// unlink defensively to avoid "address already in use".
		os.Remove(fmt.Sprintf("/var/run/php/php%s-fpm-%s.sock", phpVersion, domain))
	}

	// Write/update the cgroup limits drop-in.
	if err := writeLimitsDropIn(domain, cpuPct, memMB); err != nil {
		return err
	}
	exec.Command("systemctl", "daemon-reload").Run()

	svc := serviceName(domain)
	if alreadyIsolated {
		// Re-apply limits live + bounce to pick up the drop-in.
		exec.Command("systemctl", "restart", svc).Run()
	} else {
		out, err := exec.Command("systemctl", "enable", "--now", svc).CombinedOutput()
		if err != nil {
			// Rollback: restore shared pool so the site keeps serving.
			slog.Error("dedicated FPM failed to start, rolling back", "domain", domain, "err", string(out))
			os.Rename(disabledPool, sharedPool)
			exec.Command("systemctl", "reload", fmt.Sprintf("php%s-fpm", phpVersion)).Run()
			os.RemoveAll(siteDir)
			os.Remove(fmt.Sprintf("%s/%s.env", wpmFPMDir, domain))
			os.RemoveAll(dropInDir(domain))
			return fmt.Errorf("start %s: %s", svc, string(out))
		}
	}

	slog.Info("Resource limit applied", "domain", domain, "cpu_pct", cpuPct, "mem_mb", memMB)
	return nil
}

// RemoveResourceLimit stops the dedicated service and returns the site to the
// shared PHP-FPM pool. No-op if the site is not isolated.
func RemoveResourceLimit(domain, phpVersion string) error {
	if !phpVerRe.MatchString(phpVersion) {
		return fmt.Errorf("invalid php version %q", phpVersion)
	}
	if !serviceExists(domain) {
		return nil // not isolated, nothing to do
	}

	svc := serviceName(domain)
	exec.Command("systemctl", "disable", "--now", svc).Run()

	sharedPool := fmt.Sprintf("/etc/php/%s/fpm/pool.d/%s.conf", phpVersion, domain)
	disabledPool := sharedPool + ".disabled"
	if _, err := os.Stat(disabledPool); err == nil {
		os.Rename(disabledPool, sharedPool)
	} else {
		// Disabled pool lost — reconstruct from the dedicated copy.
		if c, err := os.ReadFile(fmt.Sprintf("%s/%s/pool.conf", wpmFPMDir, domain)); err == nil {
			os.WriteFile(sharedPool, c, 0644)
		}
	}
	exec.Command("systemctl", "reload", fmt.Sprintf("php%s-fpm", phpVersion)).Run()

	// Cleanup
	os.RemoveAll(fmt.Sprintf("%s/%s", wpmFPMDir, domain))
	os.Remove(fmt.Sprintf("%s/%s.env", wpmFPMDir, domain))
	os.RemoveAll(dropInDir(domain))
	exec.Command("systemctl", "daemon-reload").Run()

	slog.Info("Resource limit removed, site back on shared pool", "domain", domain)
	return nil
}

// writeLimitsDropIn writes the systemd drop-in with cgroup limits.
// MemoryHigh is set to 90% of MemoryMax as a soft throttle before the hard
// OOM-kill at MemoryMax (smoother behaviour under pressure).
func writeLimitsDropIn(domain string, cpuPct uint, memMB uint64) error {
	dir := dropInDir(domain)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("mkdir drop-in: %w", err)
	}
	var b strings.Builder
	b.WriteString("# Auto-generated by wp-manage\n[Service]\n")
	if cpuPct > 0 {
		fmt.Fprintf(&b, "CPUQuota=%d%%\n", cpuPct)
	} else {
		b.WriteString("CPUQuota=\n") // reset to unlimited
	}
	if memMB > 0 {
		fmt.Fprintf(&b, "MemoryMax=%dM\n", memMB)
		high := memMB * 9 / 10
		if high < 1 {
			high = memMB
		}
		fmt.Fprintf(&b, "MemoryHigh=%dM\n", high)
	} else {
		b.WriteString("MemoryMax=\nMemoryHigh=\n")
	}
	return os.WriteFile(dir+"/limits.conf", []byte(b.String()), 0644)
}

func serviceName(domain string) string { return fmt.Sprintf("wpm-fpm@%s.service", domain) }
func dropInDir(domain string) string {
	return fmt.Sprintf("/etc/systemd/system/wpm-fpm@%s.service.d", domain)
}

// serviceExists reports whether the dedicated service is currently installed
// for this domain (drop-in dir present is our marker).
func serviceExists(domain string) bool {
	if _, err := os.Stat(fmt.Sprintf("%s/%s.env", wpmFPMDir, domain)); err == nil {
		return true
	}
	return false
}
