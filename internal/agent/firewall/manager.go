// EnsureUFWInstalled installs and enables UFW if not present.
// CRITICAL: pre-allows SSH (22), HTTP (80), HTTPS (443), and Agent (8443)
// before enabling to avoid being locked out of the server.
func EnsureUFWInstalled() error {
	if _, err := exec.LookPath("ufw"); err == nil {
		return nil // already installed
	}

	slog.Info("UFW not found, installing...")
	out, err := exec.Command("apt-get", "install", "-y", "ufw").CombinedOutput()
	if err != nil {
		return fmt.Errorf("failed to install ufw: %s: %w", string(out), err)
	}

	// Pre-allow critical ports BEFORE enabling to avoid SSH lockout
	critical := []string{"22/tcp", "80/tcp", "443/tcp", "8443/tcp"}
	for _, rule := range critical {
		if out, err := exec.Command("ufw", "allow", rule).CombinedOutput(); err != nil {
			slog.Warn("Failed to pre-allow port", "rule", rule, "error", string(out))
		}
	}

	// Enable UFW non-interactively
	out, err = exec.Command("ufw", "--force", "enable").CombinedOutput()
	if err != nil {
		return fmt.Errorf("failed to enable ufw: %s: %w", string(out), err)
	}

	slog.Info("UFW installed and enabled")
	return nil
}

// EnsureEnabled ensures UFW is active even if already installed
func EnsureEnabled() {
	out, _ := exec.Command("ufw", "status").Output()
	if strings.Contains(string(out), "inactive") {
		// Pre-allow critical ports before enabling
		for _, rule := range []string{"22/tcp", "80/tcp", "443/tcp", "8443/tcp"} {
			exec.Command("ufw", "allow", rule).Run()
		}
		exec.Command("ufw", "--force", "enable").Run()
		slog.Info("UFW enabled")
	}
}

// AddRule adds a UFW firewall rule
func AddRule(ruleType, protocol, port, source, comment string) error {
	args := buildUFWArgs(ruleType, protocol, port, source, comment)
	slog.Info("Adding firewall rule", "args", strings.Join(args, " "))

	cmd := exec.Command("ufw", args...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("ufw %s failed: %s (%w)", strings.Join(args, " "), string(out), err)
	}
	slog.Info("Firewall rule added", "output", strings.TrimSpace(string(out)))
	return nil
}

// DeleteRule removes a UFW firewall rule
func DeleteRule(ruleType, protocol, port, source string) error {
	args := []string{"delete"}
	args = append(args, buildUFWArgs(ruleType, protocol, port, source, "")...)
	slog.Info("Deleting firewall rule", "args", strings.Join(args, " "))

	cmd := exec.Command("ufw", args...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("ufw delete failed: %s (%w)", string(out), err)
	}
	slog.Info("Firewall rule deleted", "output", strings.TrimSpace(string(out)))
	return nil
}

// GetStatus returns current UFW status and rules
func GetStatus() (string, error) {
	cmd := exec.Command("ufw", "status", "numbered")
	out, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("ufw status failed: %s (%w)", string(out), err)
	}
	return strings.TrimSpace(string(out)), nil
}

// ==================== Cloudflare-only mode ====================

const cfComment = "wp-manage:cloudflare"
const cfDenyComment = "wp-manage:cloudflare-deny"
const cfNginxRealIPConf = "/etc/nginx/conf.d/cloudflare-real-ip.conf"

// EnsureNginxRealIP writes (or overwrites) /etc/nginx/conf.d/cloudflare-real-ip.conf
// with set_real_ip_from directives for every Cloudflare CIDR so that Nginx resolves
// CF-Connecting-IP as the visitor's real IP instead of Cloudflare's edge IP.
// Called on Enable and Sync so the file is always in sync with UFW rules.
func EnsureNginxRealIP(ipv4s, ipv6s []string) error {
	var b strings.Builder
	b.WriteString("# Cloudflare Real IP — auto-generated by wp-manage, do not edit\n")
	b.WriteString("# Updated on: ")
	b.WriteString(strings.ReplaceAll(fmt.Sprintf("%v", os.Getenv("HOSTNAME")), "\n", ""))
	b.WriteString("\n")
	for _, cidr := range ipv4s {
		fmt.Fprintf(&b, "set_real_ip_from %s;\n", cidr)
	}
	for _, cidr := range ipv6s {
		fmt.Fprintf(&b, "set_real_ip_from %s;\n", cidr)
	}
	b.WriteString("real_ip_header CF-Connecting-IP;\n")
	b.WriteString("real_ip_recursive on;\n")

	if err := os.WriteFile(cfNginxRealIPConf, []byte(b.String()), 0644); err != nil {
		return fmt.Errorf("write cloudflare-real-ip.conf: %w", err)
	}

	// Test nginx config before reload
	if out, err := exec.Command("nginx", "-t").CombinedOutput(); err != nil {
		return fmt.Errorf("nginx -t failed after writing real IP conf: %s", string(out))
	}
	exec.Command("systemctl", "reload", "nginx").Run()
	slog.Info("CloudflareFirewall: Nginx real IP config updated", "ipv4s", len(ipv4s), "ipv6s", len(ipv6s))
	return nil
}

// EnableCloudflareOnly restricts ports 80 and 443 to Cloudflare IP ranges only.
// It removes existing catch-all allow rules, adds per-CIDR allow rules for each
// Cloudflare IP, then appends a catch-all deny for both ports.
func EnableCloudflareOnly(ipv4s, ipv6s []string) error {
	// Remove existing catch-all allow rules for 80 and 443
	for _, port := range []string{"80", "443"} {
		exec.Command("ufw", "delete", "allow", port+"/tcp").Run()
		exec.Command("ufw", "delete", "allow", port).Run()
	}

	// Allow each Cloudflare CIDR on ports 80 and 443
	all := append(ipv4s, ipv6s...)
	for _, cidr := range all {
		for _, port := range []string{"80", "443"} {
			args := []string{"allow", "from", cidr, "to", "any", "port", port, "proto", "tcp", "comment", cfComment}
			if out, err := exec.Command("ufw", args...).CombinedOutput(); err != nil {
				slog.Warn("CloudflareFirewall: failed to allow CIDR", "cidr", cidr, "port", port, "err", strings.TrimSpace(string(out)))
			}
		}
	}

	// Deny all other traffic to 80/443 (catch-all placed after specific allows)
	for _, port := range []string{"80", "443"} {
		args := []string{"deny", "from", "any", "to", "any", "port", port, "proto", "tcp", "comment", cfDenyComment}
		exec.Command("ufw", args...).Run()
	}

	exec.Command("ufw", "reload").Run()

	// Write Nginx real IP config so CF-Connecting-IP is used as visitor IP
	if err := EnsureNginxRealIP(ipv4s, ipv6s); err != nil {
		slog.Warn("CloudflareFirewall: failed to write Nginx real IP config", "err", err)
	}

	slog.Info("CloudflareFirewall: enabled", "ipv4s", len(ipv4s), "ipv6s", len(ipv6s))
	return nil
}

// DisableCloudflareOnly removes Cloudflare-only restrictions and restores
// open access on ports 80 and 443.
func DisableCloudflareOnly() error {
	if err := deleteRulesByComment(cfComment); err != nil {
		slog.Warn("CloudflareFirewall: error removing CF allow rules", "err", err)
	}
	if err := deleteRulesByComment(cfDenyComment); err != nil {
		slog.Warn("CloudflareFirewall: error removing CF deny rules", "err", err)
	}

	// Restore open allow for 80 and 443
	exec.Command("ufw", "allow", "80/tcp").Run()
	exec.Command("ufw", "allow", "443/tcp").Run()

	exec.Command("ufw", "reload").Run()
	slog.Info("CloudflareFirewall: disabled — 80/443 restored to open access")
	return nil
}

// SyncCloudflareIPs atomically replaces Cloudflare allow rules with the latest
// IP list. Deny catch-all rules are preserved; only the per-CIDR allow rules
// are replaced.
func SyncCloudflareIPs(ipv4s, ipv6s []string) error {
	// Remove old CF allow rules only (keep deny catch-alls in place)
	if err := deleteRulesByComment(cfComment); err != nil {
		slog.Warn("CloudflareFirewall: error removing old CF rules for sync", "err", err)
	}

	// Re-add updated IP list
	all := append(ipv4s, ipv6s...)
	for _, cidr := range all {
		for _, port := range []string{"80", "443"} {
			args := []string{"allow", "from", cidr, "to", "any", "port", port, "proto", "tcp", "comment", cfComment}
			if out, err := exec.Command("ufw", args...).CombinedOutput(); err != nil {
				slog.Warn("CloudflareFirewall: failed to allow CIDR during sync", "cidr", cidr, "port", port, "err", strings.TrimSpace(string(out)))
			}
		}
	}

	exec.Command("ufw", "reload").Run()

	// Update Nginx real IP config with fresh IP list
	if err := EnsureNginxRealIP(ipv4s, ipv6s); err != nil {
		slog.Warn("CloudflareFirewall: failed to update Nginx real IP config during sync", "err", err)
	}

	slog.Info("CloudflareFirewall: IPs synced", "ipv4s", len(ipv4s), "ipv6s", len(ipv6s))
	return nil
}

// deleteRulesByComment finds and deletes all UFW rules whose line contains
// the given comment tag. Deletions are done in descending rule-number order
// so that earlier numbers are not shifted by prior deletions.
func deleteRulesByComment(commentTag string) error {
	out, err := exec.Command("ufw", "status", "numbered").Output()
	if err != nil {
		return fmt.Errorf("ufw status: %w", err)
	}

	re := regexp.MustCompile(`\[\s*(\d+)\].*` + regexp.QuoteMeta(commentTag))
	var nums []int
	for _, line := range strings.Split(string(out), "\n") {
		m := re.FindStringSubmatch(line)
		if len(m) > 1 {
			n, _ := strconv.Atoi(m[1])
			if n > 0 {
				nums = append(nums, n)
			}
		}
	}

	// Sort descending so deleting rule N doesn't shift lower numbers
	sort.Sort(sort.Reverse(sort.IntSlice(nums)))
	for _, n := range nums {
		exec.Command("ufw", "--force", "delete", strconv.Itoa(n)).Run()
	}
	return nil
}

// buildUFWArgs constructs UFW command arguments
func buildUFWArgs(ruleType, protocol, port, source, comment string) []string {
	var args []string

	args = append(args, ruleType) // allow or deny

	if source != "" {
		args = append(args, "from", source)
	}

	args = append(args, "to", "any")

	if protocol == "both" {
		args = append(args, "port", port)
	} else {
		args = append(args, "port", port, "proto", protocol)
	}

	if comment != "" {
		args = append(args, "comment", comment)
	}

	return args
}
