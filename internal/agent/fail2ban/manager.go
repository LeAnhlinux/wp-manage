package fail2ban

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"strconv"
	"strings"
)

const jailConfigPath = "/etc/fail2ban/jail.d/wp-manage.conf"
const wpFilterPath = "/etc/fail2ban/filter.d/wordpress.conf"

// wpFilterContent detects WordPress login brute-force from nginx access log.
const wpFilterContent = `[Definition]
failregex = ^<HOST> .* "POST /wp-login\.php
            ^<HOST> .* "POST /xmlrpc\.php
ignoreregex =
`

// defaultJailsConfig enables SSH + nginx + WordPress jails.
// Notes:
//   - [sshd] uses backend=systemd: modern Ubuntu/Debian log SSH auth to the
//     journal, not /var/log/auth.log, so the file backend crashes fail2ban with
//     "Have not found any log file for sshd jail". This also overrides the
//     distro default (jail.d/defaults-debian.conf) that uses the file backend.
//   - nginx-bad-request is intentionally omitted: its filter isn't shipped on
//     every fail2ban build, which produces config errors.
//   - Nginx log glob covers all vhosts managed by wp-manage.
const defaultJailsConfig = `# WP Manage — default Fail2Ban jails
# Generated by wp-manage-agent. Do not edit manually.

[sshd]
enabled  = true
backend  = systemd
maxretry = 5
bantime  = 3600

[nginx-http-auth]
enabled  = true
port     = http,https
filter   = nginx-http-auth
logpath  = /var/log/nginx/*error.log
maxretry = 5
bantime  = 3600

[nginx-botsearch]
enabled  = true
port     = http,https
filter   = nginx-botsearch
logpath  = /var/log/nginx/*error.log
maxretry = 2
bantime  = 86400

[wordpress]
enabled  = true
port     = http,https
filter   = wordpress
logpath  = /var/log/nginx/*access.log
maxretry = 5
bantime  = 3600
findtime = 600
`

// SetupDefaultJails writes WordPress filter + jail configs for nginx/WordPress,
// then reloads fail2ban. Idempotent — safe to call multiple times.
func SetupDefaultJails() error {
	// Ensure the nginx log files the jails watch actually exist — otherwise
	// fail2ban aborts on startup with "Have not found any log file for <jail>".
	_ = os.MkdirAll("/var/log/nginx", 0755)
	for _, f := range []string{"/var/log/nginx/error.log", "/var/log/nginx/access.log"} {
		if _, err := os.Stat(f); os.IsNotExist(err) {
			if fh, e := os.OpenFile(f, os.O_CREATE|os.O_WRONLY, 0640); e == nil {
				fh.Close()
			}
		}
	}

	// Write WordPress filter
	if err := os.WriteFile(wpFilterPath, []byte(wpFilterContent), 0644); err != nil {
		return fmt.Errorf("write wordpress filter: %w", err)
	}

	// Write jail config
	if err := os.WriteFile(jailConfigPath, []byte(defaultJailsConfig), 0644); err != nil {
		return fmt.Errorf("write jail config: %w", err)
	}

	// Restart (not reload): applies the new config even when fail2ban is
	// currently stopped or in a failed state (reload only works while running).
	if out, err := exec.Command("systemctl", "restart", "fail2ban").CombinedOutput(); err != nil {
		return fmt.Errorf("fail2ban restart: %s", strings.TrimSpace(string(out)))
	}
	return nil
}

type JailStatus struct {
	Name      string   `json:"name"`
	Enabled   bool     `json:"enabled"`
	Filter    string   `json:"filter"`
	BanTime   int      `json:"ban_time"`
	MaxRetry  int      `json:"max_retry"`
	BannedIPs []string `json:"banned_ips"`
	TotalBans int      `json:"total_bans"`
}

// IsServiceRunning returns true if fail2ban systemd service is active.
func IsServiceRunning() bool {
	out, err := exec.Command("systemctl", "is-active", "fail2ban").Output()
	return err == nil && strings.TrimSpace(string(out)) == "active"
}

// ToggleService starts or stops the fail2ban systemd service.
func ToggleService(enable bool) error {
	var cmd *exec.Cmd
	if enable {
		cmd = exec.Command("systemctl", "enable", "--now", "fail2ban")
	} else {
		cmd = exec.Command("systemctl", "disable", "--now", "fail2ban")
	}
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("systemctl: %s", strings.TrimSpace(string(out)))
	}
	return nil
}

// configuredJails returns all jail names from wp-manage jail config file.
// This includes stopped jails that won't appear in fail2ban-client status.
func configuredJails() []string {
	data, err := os.ReadFile(jailConfigPath)
	if err != nil {
		return nil
	}
	var names []string
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			name := line[1 : len(line)-1]
			if name != "" && !strings.EqualFold(name, "DEFAULT") {
				names = append(names, name)
			}
		}
	}
	return names
}

// runningJails returns the set of jail names currently active in fail2ban.
func runningJails() map[string]bool {
	out, err := exec.Command("fail2ban-client", "status").Output()
	if err != nil {
		return map[string]bool{}
	}
	running := map[string]bool{}
	for _, line := range strings.Split(string(out), "\n") {
		if strings.Contains(line, "Jail list:") {
			parts := strings.SplitN(line, ":", 2)
			if len(parts) == 2 {
				for _, n := range strings.Split(strings.TrimSpace(parts[1]), ",") {
					n = strings.TrimSpace(n)
					if n != "" {
						running[n] = true
					}
				}
			}
		}
	}
	return running
}

// GetStatus returns ALL configured jails (running + stopped).
// Stopped jails show enabled=false so the UI can still toggle them back on.
func GetStatus() ([]JailStatus, error) {
	// Merge: configured jails (from file) + any extra running jails (e.g. sshd from defaults-debian.conf)
	fromFile := configuredJails()
	running := runningJails()

	// Build union of jail names: file-configured + running
	seen := map[string]bool{}
	var allNames []string
	for _, n := range fromFile {
		if !seen[n] {
			allNames = append(allNames, n)
			seen[n] = true
		}
	}
	for n := range running {
		if !seen[n] {
			allNames = append(allNames, n)
			seen[n] = true
		}
	}

	var jails []JailStatus
	for _, name := range allNames {
		jail := JailStatus{
			Name:      name,
			Enabled:   running[name],
			BannedIPs: []string{},
		}

		// Only query live data for running jails
		if running[name] {
			jailOut, err := exec.Command("fail2ban-client", "status", name).Output()
			if err == nil {
				for _, line := range strings.Split(string(jailOut), "\n") {
					line = strings.TrimSpace(line)
					if strings.Contains(line, "Banned IP list:") {
						parts := strings.SplitN(line, ":", 2)
						if len(parts) == 2 {
							jail.BannedIPs = strings.Fields(strings.TrimSpace(parts[1]))
						}
					}
					if strings.Contains(line, "Currently banned:") {
						parts := strings.SplitN(line, ":", 2)
						if len(parts) == 2 {
							jail.TotalBans, _ = strconv.Atoi(strings.TrimSpace(parts[1]))
						}
					}
				}
			}
		}

		jails = append(jails, jail)
	}

	return jails, nil
}

// UnbanIP unbans an IP from a specific jail.
func UnbanIP(jail, ip string) error {
	out, err := exec.Command("fail2ban-client", "set", jail, "unbanip", ip).CombinedOutput()
	if err != nil {
		return fmt.Errorf("unban %s from %s: %s", ip, jail, string(out))
	}
	return nil
}

// UpdateJail updates jail configuration (enable/disable, ban time, max retry).
func UpdateJail(jail string, enabled *bool, banTime, maxRetry int) error {
	if enabled != nil {
		if *enabled {
			exec.Command("fail2ban-client", "start", jail).Run()
		} else {
			exec.Command("fail2ban-client", "stop", jail).Run()
		}
	}
	if banTime > 0 {
		exec.Command("fail2ban-client", "set", jail, "bantime", strconv.Itoa(banTime)).Run()
	}
	if maxRetry > 0 {
		exec.Command("fail2ban-client", "set", jail, "maxretry", strconv.Itoa(maxRetry)).Run()
	}
	return nil
}

// StatusJSON returns full status as JSON: { service_running, jails }.
// If service is stopped, jails will be empty but no error is returned.
func StatusJSON() (json.RawMessage, error) {
	running := IsServiceRunning()
	var jails []JailStatus
	if running {
		var err error
		jails, err = GetStatus()
		if err != nil {
			// Service running but client failed — still report running=true
			jails = []JailStatus{}
		}
	} else {
		jails = []JailStatus{}
	}
	return json.Marshal(map[string]interface{}{
		"service_running": running,
		"jails":           jails,
	})
}
